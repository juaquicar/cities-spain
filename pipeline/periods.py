PERIODS = [(k, l, a, b, c) for (k, l, a, b), c in zip(LABELS.get(REGION.key, GENERIC), COLORS)]


def period_of(year: int) -> int:
    for i, (_, _, a, b, _) in enumerate(PERIODS):
        if a <= year <= b:
            return i
    return 0 if year < PERIODS[0][2] else len(PERIODS) - 1
